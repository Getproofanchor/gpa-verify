def _poc_forged_witness_zip() -> bytes:
    """audit PoC (witness_forge.py): a one-step witness from our entry
    straight to someone else's anchored head at seq 500."""
    H = lambda b: hashlib.sha256(b).hexdigest()  # noqa: E731
    pid = "11111111-1111-1111-1111-111111111111"
    data_hash = H(b"anything")
    eh = H(f"|proof_created|{pid}|{data_hash}".encode())
    entry = {"seq": 10, "event_type": "proof_created", "proof_id": pid, "data_hash": data_hash,
             "prev_hash": None, "entry_hash": eh, "created_at": "2026-01-01T00:00:00Z"}
    anchored_head = "ab" * 32
    ap = _canon({"v": 2, "seq": 500, "head": anchored_head})
    files = {
        "proof.json": json.dumps({"proof_id": pid, "anchor": {"head_seq": 500, "head_hash": anchored_head,
                                                              "payload_sha256": H(ap)}, "ots": {}}).encode(),
        "chain/proof_chain.jsonl": (json.dumps(entry) + "\n").encode(),
        "chain/chain_head.json": json.dumps({"seq": 10, "entry_hash": eh}).encode(),
        "chain/anchor_witness.jsonl": json.dumps({"seq": 11, "prev_hash": eh,
                                                  "entry_hash": anchored_head}).encode() + b"\n",
        "anchor/anchor_payload.json": ap,
    }
    man = {"format": "getproofanchor-evidence-4", "proof_id": pid,
           "anchor": {"present": True, "payload_sha256": H(ap)},
           "files": {k: {"sha256": H(v), "size": len(v)} for k, v in files.items()}}
    out = io.BytesIO()
    with zipfile.ZipFile(out, "w") as z:
        for k, v in files.items():
            z.writestr(k, v)
        z.writestr("manifest.json", json.dumps(man))
    return out.getvalue()


def test_poc_forged_witness_no_longer_links():
    report = verify_evidence_zip(_poc_forged_witness_zip())
    w = _check(report, "anchor_witness")
    assert not w.passed and w.skipped
    assert w.detail.startswith("informational (not independently recomputable)")
    assert w.extra["last_witness_seq"] == 11 and w.extra["anchor_seq"] == 500
    assert _check(report, "anchor_inclusion").extra["result"] == "not_present"


