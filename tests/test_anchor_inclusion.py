def test_bitcoin_rpc_checks_content_anchor_receipt(monkeypatch):
    """Review S2: --bitcoin-rpc verifies the CONTENT anchor receipt too."""
    import gpa_verify.core as core
    seen = []

    def fake(receipt, rpc):
        seen.append(receipt)
        return {"verified_heights": [870001], "bitcoin_attestations": [870001], "errors": [],
                "block_times": {870001: 1}}
    monkeypatch.setattr(core, "_bitcoin_verify_via_node", fake)
    data = V3_LATER.read_bytes()
    rc = zipfile.ZipFile(io.BytesIO(data)).read("anchor/inclusion_anchor_receipt.ots")
    report = verify_evidence_zip(data, bitcoin_rpc="http://u:p@127.0.0.1:8332")
    c = _check(report, "anchor_inclusion")
    assert rc in seen
    assert c.passed and c.extra["bitcoin_attestation_verified"] is True
    assert c.extra["verified_block_heights"] == [870001]

    def fake_fail(receipt, rpc):
        return {"verified_heights": [], "bitcoin_attestations": [870001], "errors": ["merkle mismatch"]}
    monkeypatch.setattr(core, "_bitcoin_verify_via_node", fake_fail)
    c = _check(verify_evidence_zip(data, bitcoin_rpc="http://x"), "anchor_inclusion")
    assert c.extra["result"] == "failed" and c.extra["bitcoin_verification"] == "node_failed"


