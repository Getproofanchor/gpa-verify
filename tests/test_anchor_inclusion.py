def _check(report, name):
    return next(c for c in report.checks if c.name == name)


def _rezip(data: bytes, mutate) -> bytes:
    zin = zipfile.ZipFile(io.BytesIO(data))
    files = {n: zin.read(n) for n in zin.namelist()}
    manifest = json.loads(files.pop("manifest.json"))
    mutate(files, manifest)
    manifest["files"] = {k: {"sha256": hashlib.sha256(v).hexdigest(), "size": len(v)}
                         for k, v in files.items()}
    out = io.BytesIO()
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        for k, v in files.items():
            z.writestr(k, v)
        z.writestr("manifest.json", json.dumps(manifest, indent=2))
    return out.getvalue()


def _canon(o):
    return json.dumps(o, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode()


def graft_inclusion(data: bytes, n_leaves: int = 5, index: int = 2) -> bytes:
    """Add a v3 inclusion proof (own tree, own v3 anchor payload, stub OTS
    receipt) to a real bundle, as the server does for a later anchor."""
    def mut(files, manifest):
        pid = manifest["proof_id"]
        sha = hashlib.sha256(files["timestamp/eidas_payload.json"]).hexdigest()
        leaf = anchor_leaf_v3(pid, sha)
        leaves = [_H(bytes([i])) for i in range(n_leaves)]
        leaves[index] = leaf
        root = _mth(leaves).hex()
        ap = {"v": 3, "seq": 1, "head": "ab" * 32, "observed_at_utc": "2026-10-21T10:00:00Z",
              "covers_from_seq": 2, "covers_to_seq": 1, "merkle_root": root, "leaf_count": n_leaves,
              "leaf_algo": "gpa-anchor-leaf-v3"}
        apb = _canon(ap)
        ap_sha = hashlib.sha256(apb).hexdigest()
        files["anchor/inclusion_anchor_payload.json"] = apb
        # header + one PendingAttestation-looking tail (a stub, not Bitcoin-attested)
        files["anchor/inclusion_anchor_receipt.ots"] = (OTS_MAGIC + b"\x01\x08" + bytes.fromhex(ap_sha) + b"\x00"
                                                        + bytes.fromhex("83dfe30d2ef90c8e") + b"\x01\x00")
        files["anchor/inclusion.json"] = json.dumps({
            "format": "gpa-anchor-inclusion-1", "proof_id": pid, "leaf_algo": "gpa-anchor-leaf-v3",
            "tree_algo": "rfc6962-sha256", "eidas_payload_file": "timestamp/eidas_payload.json",
            "eidas_payload_sha256": sha, "leaf_hash": leaf.hex(), "leaf_index": index,
            "leaf_count": n_leaves, "audit_path": _path(index, leaves), "merkle_root": root,
            "anchor_id": 1, "anchor_payload": ap, "anchor_payload_sha256": ap_sha,
            "anchor_payload_file": "anchor/inclusion_anchor_payload.json",
            "anchor_receipt_file": "anchor/inclusion_anchor_receipt.ots",
        }, indent=2).encode()
    return _rezip(data, mut)


