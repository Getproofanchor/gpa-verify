@pytest.mark.parametrize("n", sorted(CT_ROOTS))
def test_rfc6962_vectors_via_paths(n):
    leaves = CT_LEAVES[:n]
    assert _mth(leaves).hex() == CT_ROOTS[n]
    for i in range(n):
        assert merkle_root_from_path(leaves[i], i, n, _path(i, leaves)).hex() == CT_ROOTS[n]


@pytest.mark.parametrize("n", [2, 3, 5, 8, 13])
def test_path_tampering_rejected(n):
    leaves = [_H(bytes([i])) for i in range(n)]
    root = _mth(leaves)
    for i in range(n):
        p = _path(i, leaves)
        assert merkle_root_from_path(leaves[i], i, n, p) == root
        assert merkle_root_from_path(_H(b"x"), i, n, p) != root
        assert merkle_root_from_path(leaves[i], n, n, p) is None
        bad = copy.deepcopy(p)
        bad[0]["side"] = "L" if bad[0]["side"] == "R" else "R"
        assert merkle_root_from_path(leaves[i], i, n, bad) is None
        bad = copy.deepcopy(p)
        bad[0]["hash"] = "00" * 32
        assert merkle_root_from_path(leaves[i], i, n, bad) != root
        assert merkle_root_from_path(leaves[i], i, n, p[:-1]) != root
        assert merkle_root_from_path(leaves[i], True, n, p) is None


