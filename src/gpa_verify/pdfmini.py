"""
gpa_verify.pdfmini — a deliberately small, read-only PDF parser.

Only what offline PAdES / attachment verification needs:

  * tokenizer and object parser (dicts, arrays, names, strings, numbers,
    references, streams);
  * cross-reference tables AND cross-reference streams, object streams,
    /Prev chains and hybrid /XRefStm files;
  * revision boundaries (``%%EOF`` markers) so incremental updates can be
    attributed to the revision that introduced them;
  * stream decoding for FlateDecode (with PNG/TIFF predictors),
    ASCIIHexDecode and ASCII85Decode;
  * name-tree traversal (/EmbeddedFiles) and page-tree traversal;
  * a plain text extractor for simple content streams with ToUnicode
    CMaps (enough for the GetProofAnchor reports generated by ReportLab).

No rendering, no encryption support (encrypted files are reported as
such), no repair heuristics beyond a last-resort object scan. Everything
here operates on immutable bytes; nothing is ever written back.
"""

from __future__ import annotations

import re
import zlib
from dataclasses import dataclass, field
from typing import Any, Dict, Iterator, List, Optional, Tuple

# ─────────────────────────────────────────────────────────────────────────────
# Object model
# ─────────────────────────────────────────────────────────────────────────────


class PDFError(Exception):
    """Raised for structurally invalid PDF data."""


class Name(str):
    """A PDF name object (stored without the leading slash)."""

    def __repr__(self) -> str:  # pragma: no cover - debugging aid
        return "/" + str(self)


@dataclass(frozen=True)
class Ref:
    num: int
    gen: int = 0


@dataclass
class Stream:
    dict: Dict[str, Any]
    raw: bytes
    offset: int = -1          # file offset of the raw stream data

    def get(self, key: str, default: Any = None) -> Any:
        return self.dict.get(key, default)


class PDFString(bytes):
    """A PDF string object (literal or hex). Raw bytes, undecoded."""

    is_hex: bool = False

    def text(self) -> str:
        """Best-effort text decoding (UTF-16BE BOM, UTF-8 BOM, else PDFDoc≈latin-1)."""
        b = bytes(self)
        if b.startswith(b"\xfe\xff"):
            return b[2:].decode("utf-16-be", errors="replace")
        if b.startswith(b"\xef\xbb\xbf"):
            return b[3:].decode("utf-8", errors="replace")
        return b.decode("latin-1")


_WS = b" \t\r\n\f\x00"
_DELIM = b"()<>[]{}/%"
_WS_SET = frozenset(_WS)
_DELIM_SET = frozenset(_DELIM)
_REGULAR_END = _WS_SET | _DELIM_SET


# ─────────────────────────────────────────────────────────────────────────────
# Lexer / parser
# ─────────────────────────────────────────────────────────────────────────────


class Lexer:
    def __init__(self, data: bytes, pos: int = 0, end: Optional[int] = None):
        self.data = data
        self.pos = pos
        self.end = len(data) if end is None else end

    def skip_ws(self) -> None:
        d, p, e = self.data, self.pos, self.end
        while p < e:
            c = d[p]
            if c in _WS_SET:
                p += 1
            elif c == 0x25:  # '%' comment to EOL
                while p < e and d[p] not in (0x0A, 0x0D):
                    p += 1
            else:
                break
        self.pos = p

    def next_token(self) -> Any:
        """Return the next token. Keywords are returned as ``bytes``."""
        self.skip_ws()
        d, p = self.data, self.pos
        if p >= self.end:
            return None
        c = d[p]
        if c == 0x2F:  # '/'
            q = p + 1
            while q < self.end and d[q] not in _REGULAR_END:
                q += 1
            raw = d[p + 1:q]
            self.pos = q
            if b"#" in raw:
                raw = re.sub(rb"#([0-9A-Fa-f]{2})", lambda m: bytes([int(m.group(1), 16)]), raw)
            return Name(raw.decode("latin-1"))
        if c == 0x28:  # '('
            return self._literal_string()
        if c == 0x3C:  # '<'
            if p + 1 < self.end and d[p + 1] == 0x3C:
                self.pos = p + 2
                return b"<<"
            return self._hex_string()
        if c == 0x3E:
            if p + 1 < self.end and d[p + 1] == 0x3E:
                self.pos = p + 2
                return b">>"
            self.pos = p + 1
            return b">"
        if c in (0x5B, 0x5D, 0x7B, 0x7D):
            self.pos = p + 1
            return bytes([c])
        q = p
        while q < self.end and d[q] not in _REGULAR_END:
            q += 1
        if q == p:  # stray delimiter such as ')'
            self.pos = p + 1
            return bytes([c])
        tok = d[p:q]
        self.pos = q
        if re.fullmatch(rb"[+-]?\d+", tok):
            return int(tok)
        if re.fullmatch(rb"[+-]?(\d+\.\d*|\.\d+|\d+\.)", tok):
            return float(tok)
        return tok  # keyword

    def _literal_string(self) -> PDFString:
        d = self.data
        p = self.pos + 1
        depth = 1
        out = bytearray()
        while p < self.end:
            c = d[p]
            if c == 0x5C:  # backslash
                p += 1
                if p >= self.end:
                    break
                e = d[p]
                m = {0x6E: 0x0A, 0x72: 0x0D, 0x74: 0x09, 0x62: 0x08, 0x66: 0x0C,
                     0x28: 0x28, 0x29: 0x29, 0x5C: 0x5C}
                if e in m:
                    out.append(m[e])
                    p += 1
                elif 0x30 <= e <= 0x37:
                    q = p
                    while q < self.end and q < p + 3 and 0x30 <= d[q] <= 0x37:
                        q += 1
                    out.append(int(d[p:q], 8) & 0xFF)
                    p = q
                elif e == 0x0D:
                    p += 1
                    if p < self.end and d[p] == 0x0A:
                        p += 1
                elif e == 0x0A:
                    p += 1
                else:
                    out.append(e)
                    p += 1
                continue
            if c == 0x28:
                depth += 1
            elif c == 0x29:
                depth -= 1
                if depth == 0:
                    p += 1
                    break
            out.append(c)
            p += 1
        self.pos = p
        return PDFString(bytes(out))

    def _hex_string(self) -> PDFString:
        d = self.data
        q = d.find(b">", self.pos + 1, self.end)
        if q < 0:
            raise PDFError(f"unterminated hex string at {self.pos}")
        hexs = re.sub(rb"[^0-9A-Fa-f]", b"", d[self.pos + 1:q])
        if len(hexs) % 2:
            hexs += b"0"
        self.pos = q + 1
        s = PDFString(bytes.fromhex(hexs.decode("ascii")))
        s.is_hex = True
        return s


class Parser:
    """Parses PDF objects from a byte buffer (whole file or decoded stream)."""

    def __init__(self, data: bytes, pos: int = 0, end: Optional[int] = None,
                 resolver: Optional["PDFDocument"] = None):
        self.lex = Lexer(data, pos, end)
        self.resolver = resolver
        self._pending: List[Any] = []

    @property
    def pos(self) -> int:
        return self.lex.pos

    def _tok(self) -> Any:
        if self._pending:
            return self._pending.pop()
        return self.lex.next_token()

    def _push(self, tok: Any) -> None:
        self._pending.append(tok)

    def parse_object(self) -> Any:
        tok = self._tok()
        return self._from_token(tok)

    def _from_token(self, tok: Any) -> Any:
        if tok is None:
            raise PDFError("unexpected end of data")
        if isinstance(tok, int):
            # possible "num gen R"
            t2 = self._tok()
            if isinstance(t2, int):
                t3 = self._tok()
                if t3 == b"R":
                    return Ref(tok, t2)
                self._push(t3)
                self._push(t2)
                return tok
            self._push(t2)
            return tok
        if tok == b"<<":
            out: Dict[str, Any] = {}
            while True:
                k = self._tok()
                if k == b">>":
                    break
                if k is None:
                    raise PDFError("unterminated dictionary")
                if not isinstance(k, Name):
                    # tolerate garbage: skip
                    continue
                v = self.parse_object()
                out[str(k)] = v
            return out
        if tok == b"[":
            arr: List[Any] = []
            while True:
                t = self._tok()
                if t == b"]":
                    break
                if t is None:
                    raise PDFError("unterminated array")
                arr.append(self._from_token(t))
            return arr
        if tok == b"true":
            return True
        if tok == b"false":
            return False
        if tok == b"null":
            return None
        return tok  # Name, PDFString, float, keyword bytes

    def parse_indirect_at(self, offset: int) -> Tuple[int, int, Any]:
        """Parse ``N G obj ... endobj`` at file offset; returns (num, gen, obj)."""
        self.lex.pos = offset
        self._pending.clear()
        num = self._tok()
        gen = self._tok()
        kw = self._tok()
        if not (isinstance(num, int) and isinstance(gen, int) and kw == b"obj"):
            raise PDFError(f"no indirect object at offset {offset}")
        obj = self.parse_object()
        # stream?
        self._pending.clear()
        save = self.lex.pos
        nxt = self.lex.next_token()
        if nxt == b"stream" and isinstance(obj, dict):
            d = self.lex.data
            p = self.lex.pos
            if d[p:p + 2] == b"\r\n":
                p += 2
            elif d[p:p + 1] in (b"\n", b"\r"):
                p += 1
            length = obj.get("Length")
            if isinstance(length, Ref) and self.resolver is not None:
                try:
                    length = self.resolver.resolve(length)
                except Exception:
                    length = None
            raw = None
            if isinstance(length, int) and length >= 0:
                cand_end = p + length
                tail = d[cand_end:cand_end + 32]
                if re.match(rb"\s*endstream", tail):
                    raw = d[p:cand_end]
            if raw is None:
                q = d.find(b"endstream", p)
                if q < 0:
                    raise PDFError(f"unterminated stream in object {num}")
                e = q
                if d[e - 2:e] == b"\r\n":
                    e -= 2
                elif d[e - 1:e] in (b"\n", b"\r"):
                    e -= 1
                raw = d[p:e]
            obj = Stream(obj, raw, p)
            self.lex.pos = p + len(raw)
        else:
            self.lex.pos = save
        return num, gen, obj


