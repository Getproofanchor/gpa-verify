def _parse_tounicode(data: bytes) -> Tuple[Dict[int, str], int]:
    """Parse a ToUnicode CMap; returns (code->text, code byte length)."""
    cmap: Dict[int, str] = {}
    nbytes = 1
    m = re.search(rb"begincodespacerange\s*<([0-9A-Fa-f]+)>", data)
    if m:
        nbytes = max(1, len(m.group(1)) // 2)

    def u(hexs: bytes) -> str:
        b = bytes.fromhex(hexs.decode())
        try:
            return b.decode("utf-16-be")
        except UnicodeDecodeError:
            return ""

    for blk in re.finditer(rb"beginbfchar(.*?)endbfchar", data, re.S):
        for a, b in re.findall(rb"<([0-9A-Fa-f]+)>\s*<([0-9A-Fa-f]*)>", blk.group(1)):
            cmap[int(a, 16)] = u(b)
    for blk in re.finditer(rb"beginbfrange(.*?)endbfrange", data, re.S):
        body = blk.group(1)
        for mm in re.finditer(rb"<([0-9A-Fa-f]+)>\s*<([0-9A-Fa-f]+)>\s*(<[0-9A-Fa-f]+>|\[[^\]]*\])", body):
            lo, hi = int(mm.group(1), 16), int(mm.group(2), 16)
            dst = mm.group(3)
            if dst.startswith(b"["):
                items = re.findall(rb"<([0-9A-Fa-f]*)>", dst)
                for i, it in enumerate(items):
                    cmap[lo + i] = u(it)
            else:
                base = bytes.fromhex(dst[1:-1].decode())
                for i in range(0, min(hi - lo, 65535) + 1):
                    bb = base[:-1] + bytes([(base[-1] + i) & 0xFF]) if base else b""
                    try:
                        cmap[lo + i] = bb.decode("utf-16-be")
                    except UnicodeDecodeError:
                        pass
    return cmap, nbytes


class _Font:
    def __init__(self, doc: PDFDocument, fdict: Dict[str, Any]):
        self.cmap: Optional[Dict[int, str]] = None
        self.nbytes = 1
        tu = doc.resolve(fdict.get("ToUnicode"))
        if isinstance(tu, Stream):
            try:
                self.cmap, self.nbytes = _parse_tounicode(decode_stream(tu, doc))
            except PDFError:
                self.cmap = None
        if fdict.get("Subtype") == "Type0" and self.cmap is None:
            self.nbytes = 2

    def decode(self, s: bytes) -> str:
        if self.cmap is None:
            if self.nbytes == 2:
                return ""
            return s.decode("cp1252", errors="replace")
        out = []
        n = self.nbytes
        for i in range(0, len(s) - n + 1, n):
            code = int.from_bytes(s[i:i + n], "big")
            ch = self.cmap.get(code)
            if ch is None:
                ch = chr(code) if n == 1 and 32 <= code < 127 else ""
            out.append(ch.replace("\x00", ""))
        return "".join(out)


def extract_page_text(doc: PDFDocument, page: Dict[str, Any]) -> str:
    """Very small text extractor: emits one line per text-positioning op."""
    res = doc.resolve(page.get("Resources")) or {}
    fonts_d = doc.resolve(res.get("Font")) if isinstance(res, dict) else None
    fonts: Dict[str, _Font] = {}
    if isinstance(fonts_d, dict):
        for k, v in fonts_d.items():
            fv = doc.resolve(v)
            if isinstance(fv, dict):
                fonts[k] = _Font(doc, fv)
    contents = doc.resolve(page.get("Contents"))
    parts = contents if isinstance(contents, list) else [contents]
    data = b""
    for c in parts:
        c = doc.resolve(c)
        if isinstance(c, Stream):
            try:
                data += decode_stream(c, doc) + b"\n"
            except PDFError:
                continue
    lines: List[str] = []
    cur: List[str] = []
    font: Optional[_Font] = None
    operands: List[Any] = []
    p = Parser(data)

    def flush() -> None:
        if cur:
            line = "".join(cur).strip()
            if line:
                lines.append(line)
            cur.clear()

    while True:
        try:
            tok = p._tok()
        except PDFError:
            break
        if tok is None:
            break
        if isinstance(tok, bytes) and not isinstance(tok, (PDFString,)) and tok not in (b"<<", b"[") \
                and re.fullmatch(rb"[A-Za-z'\"*]+[0-9]?\*?", tok or b"x"):
            op = tok
            if op == b"BI":  # inline image: skip to EI
                d = p.lex.data
                q = d.find(b"EI", p.lex.pos)
                p.lex.pos = q + 2 if q >= 0 else len(d)
                operands = []
                continue
            if op == b"Tf" and len(operands) >= 2 and isinstance(operands[0], Name):
                font = fonts.get(str(operands[0]))
            elif op in (b"Tj", b"'", b'"'):
                s = operands[-1] if operands else b""
                if op != b"Tj":
                    flush()
                if isinstance(s, PDFString):
                    cur.append(font.decode(s) if font else bytes(s).decode("cp1252", "replace"))
            elif op == b"TJ":
                arr = operands[-1] if operands else []
                if isinstance(arr, list):
                    for it in arr:
                        if isinstance(it, PDFString):
                            cur.append(font.decode(it) if font else bytes(it).decode("cp1252", "replace"))
                        elif isinstance(it, (int, float)) and it < -200:
                            cur.append(" ")
            elif op in (b"BT", b"ET", b"T*", b"Td", b"TD", b"Tm"):
                flush()
            operands = []
            continue
        try:
            operands.append(p._from_token(tok))
        except PDFError:
            break
    flush()
    return "\n".join(lines)


def extract_text(doc: PDFDocument) -> List[str]:
    out = []
    for pg in doc.pages():
        try:
            out.append(extract_page_text(doc, pg))
        except Exception:  # pragma: no cover - defensive, never fatal
            out.append("")
    return out


