def _png_unpredict(data: bytes, columns: int, colors: int, bpc: int) -> bytes:
    bpp = max(1, (colors * bpc + 7) // 8)
    row_len = (columns * colors * bpc + 7) // 8
    out = bytearray()
    prev = bytearray(row_len)
    i = 0
    while i < len(data):
        ft = data[i]
        row = bytearray(data[i + 1:i + 1 + row_len])
        i += 1 + row_len
        if len(row) < row_len:
            row.extend(b"\x00" * (row_len - len(row)))
        if ft == 1:
            for j in range(bpp, row_len):
                row[j] = (row[j] + row[j - bpp]) & 0xFF
        elif ft == 2:
            for j in range(row_len):
                row[j] = (row[j] + prev[j]) & 0xFF
        elif ft == 3:
            for j in range(row_len):
                left = row[j - bpp] if j >= bpp else 0
                row[j] = (row[j] + ((left + prev[j]) >> 1)) & 0xFF
        elif ft == 4:
            for j in range(row_len):
                a = row[j - bpp] if j >= bpp else 0
                b = prev[j]
                c = prev[j - bpp] if j >= bpp else 0
                pa, pb, pc = abs(b - c), abs(a - c), abs(a + b - 2 * c)
                pr = a if (pa <= pb and pa <= pc) else (b if pb <= pc else c)
                row[j] = (row[j] + pr) & 0xFF
        out.extend(row)
        prev = row
    return bytes(out)


def _apply_predictor(data: bytes, parms: Optional[Dict[str, Any]]) -> bytes:
    if not parms:
        return data
    pred = parms.get("Predictor", 1)
    if not isinstance(pred, int) or pred == 1:
        return data
    columns = parms.get("Columns", 1)
    colors = parms.get("Colors", 1)
    bpc = parms.get("BitsPerComponent", 8)
    if pred >= 10:
        return _png_unpredict(data, columns, colors, bpc)
    if pred == 2 and bpc == 8:
        row_len = columns * colors
        out = bytearray(data)
        for r in range(0, len(out), row_len):
            for j in range(colors, row_len):
                if r + j < len(out):
                    out[r + j] = (out[r + j] + out[r + j - colors]) & 0xFF
        return bytes(out)
    return data


def _ascii85(data: bytes) -> bytes:
    data = re.sub(rb"\s", b"", data)
    if data.startswith(b"<~"):
        data = data[2:]
    if data.endswith(b"~>"):
        data = data[:-2]
    out = bytearray()
    group: List[int] = []
    for c in data:
        if c == 0x7A and not group:  # 'z'
            out.extend(b"\x00\x00\x00\x00")
            continue
        group.append(c - 33)
        if len(group) == 5:
            n = 0
            for g in group:
                n = n * 85 + g
            out.extend(n.to_bytes(4, "big"))
            group = []
    if group:
        k = len(group)
        group += [84] * (5 - k)
        n = 0
        for g in group:
            n = n * 85 + g
        out.extend(n.to_bytes(4, "big")[:k - 1])
    return bytes(out)


class UnsupportedFilter(PDFError):
    pass


def decode_stream(stream: Stream, doc: Optional["PDFDocument"] = None,
                  stop_at: Tuple[str, ...] = ()) -> bytes:
    """Decode a stream's data. Image codecs (DCT, JPX, CCITT, JBIG2) are
    NOT decoded: if one is reached, UnsupportedFilter is raised unless it is
    listed in ``stop_at`` (in which case the still-encoded data is returned)."""
    def r(x):
        return doc.resolve(x) if doc is not None else x

    filters = r(stream.get("Filter"))
    parms = r(stream.get("DecodeParms"))
    if filters is None:
        return stream.raw
    if not isinstance(filters, list):
        filters = [filters]
        parms = [parms]
    elif not isinstance(parms, list):
        parms = [parms] * len(filters)
    data = stream.raw
    for f, p in zip(filters, parms):
        f = str(r(f))
        p = r(p)
        if f in ("FlateDecode", "Fl"):
            try:
                data = zlib.decompress(data)
            except zlib.error:
                try:
                    data = zlib.decompressobj().decompress(data)
                except zlib.error as exc:
                    raise PDFError(f"corrupt FlateDecode stream: {exc}") from None
            data = _apply_predictor(data, p if isinstance(p, dict) else None)
        elif f in ("ASCIIHexDecode", "AHx"):
            h = re.sub(rb"[^0-9A-Fa-f]", b"", data.split(b">")[0])
            if len(h) % 2:
                h += b"0"
            data = bytes.fromhex(h.decode())
        elif f in ("ASCII85Decode", "A85"):
            try:
                data = _ascii85(data)
            except (ValueError, OverflowError) as exc:
                raise PDFError(f"corrupt ASCII85 stream: {exc}") from None
        elif f in stop_at:
            return data
        else:
            raise UnsupportedFilter(f"unsupported filter {f}")
    return data


# ─────────────────────────────────────────────────────────────────────────────
# Document / xref
# ─────────────────────────────────────────────────────────────────────────────


@dataclass
class XrefSection:
    """One cross-reference section (table or stream) = one revision's xref."""
    offset: int                       # startxref value pointing at it
    kind: str                         # "table" | "stream"
    trailer: Dict[str, Any]
    entries: Dict[int, Tuple[str, int, int]] = field(default_factory=dict)
    # entries: num -> ("n", offset, gen) | ("c", objstm_num, index) | ("f", next, gen)
    end: int = -1                     # offset just after the section's %%EOF line


@dataclass
class Revision:
    index: int
    start: int          # first byte of this revision (0 for the original)
    end: int            # one past the last byte (after %%EOF + EOL)
    xref: Optional[XrefSection]


class PDFDocument:
    def __init__(self, data: bytes):
        self.data = data
        head = data[:1024]
        hp = head.find(b"%PDF-")
        if hp < 0:
            raise PDFError("not a PDF (no %PDF- header in the first 1024 bytes)")
        self.header_offset = hp
        self.version = head[hp + 5:hp + 8].decode("latin-1", "replace")
        self._cache: Dict[Tuple[int, int], Any] = {}
        self._objstm_cache: Dict[int, Dict[int, Any]] = {}
        self.sections: List[XrefSection] = []   # newest first
        self.xref: Dict[int, Tuple[str, int, int]] = {}
        self.trailer: Dict[str, Any] = {}
        self.warnings: List[str] = []
        self._load_xref()

    # ── EOF markers / revisions ────────────────────────────────────────────

    def eof_ends(self) -> List[int]:
        """Offsets just past every ``%%EOF`` marker (and its EOL)."""
        out = []
        for m in re.finditer(rb"%%EOF", self.data):
            e = m.end()
            if self.data[e:e + 2] == b"\r\n":
                e += 2
            elif self.data[e:e + 1] in (b"\r", b"\n"):
                e += 1
            out.append(e)
        return out

    def revisions(self) -> List[Revision]:
        """Revisions in file order, derived from the xref /Prev chain."""
        secs = sorted(self.sections, key=lambda s: s.offset)
        ends = self.eof_ends()
        revs: List[Revision] = []
        start = 0
        for i, s in enumerate(secs):
            end = next((e for e in ends if e > s.offset), len(self.data))
            s.end = end
            revs.append(Revision(i, start, end, s))
            start = end
        return revs

    # ── xref loading ───────────────────────────────────────────────────────

    def _find_startxref(self) -> int:
        tail_start = max(0, len(self.data) - 2048)
        tail = self.data[tail_start:]
        idx = tail.rfind(b"startxref")
        if idx < 0:
            raise PDFError("startxref not found")
        lex = Lexer(tail, idx + len(b"startxref"))
        v = lex.next_token()
        if not isinstance(v, int):
            raise PDFError("startxref value invalid")
        return v

    def _load_xref(self) -> None:
        try:
            off = self._find_startxref()
        except PDFError as exc:
            self.warnings.append(str(exc))
            self._rebuild_by_scan()
            return
        seen = set()
        merged: Dict[int, Tuple[str, int, int]] = {}
        first_trailer: Optional[Dict[str, Any]] = None
        queue = [off]
        while queue:
            off = queue.pop(0)
            if off in seen:
                break
            seen.add(off)
            try:
                sec = self._read_xref_section(off)
            except PDFError as exc:
                self.warnings.append(f"xref at {off}: {exc}")
                self._rebuild_by_scan()
                return
            self.sections.append(sec)
            for k, v in sec.entries.items():
                merged.setdefault(k, v)
            if first_trailer is None:
                first_trailer = sec.trailer
            stm = sec.trailer.get("XRefStm")
            if isinstance(stm, int) and stm not in seen:
                try:
                    hs = self._read_xref_section(stm)
                    seen.add(stm)
                    for k, v in hs.entries.items():
                        merged.setdefault(k, v)
                    # hybrid stream belongs to the same revision; merge into sec
                    for k, v in hs.entries.items():
                        sec.entries.setdefault(k, v)
                except PDFError as exc:
                    self.warnings.append(f"XRefStm at {stm}: {exc}")
            prev = sec.trailer.get("Prev")
            if isinstance(prev, int):
                queue.append(prev)
        self.xref = merged
        self.trailer = first_trailer or {}

    def _read_xref_section(self, off: int) -> XrefSection:
        d = self.data
        if off < 0 or off >= len(d):
            raise PDFError("offset out of range")
        lex = Lexer(d, off)
        lex.skip_ws()
        if d[lex.pos:lex.pos + 4] == b"xref":
            return self._read_xref_table(off, lex.pos + 4)
        p = Parser(d, resolver=self)
        num, gen, obj = p.parse_indirect_at(lex.pos)
        if not isinstance(obj, Stream) or obj.get("Type") != "XRef":
            raise PDFError("not an xref table or xref stream")
        return self._read_xref_stream(off, obj)

    def _read_xref_table(self, off: int, pos: int) -> XrefSection:
        d = self.data
        lex = Lexer(d, pos)
        entries: Dict[int, Tuple[str, int, int]] = {}
        while True:
            lex.skip_ws()
            if d[lex.pos:lex.pos + 7] == b"trailer":
                lex.pos += 7
                break
            start = lex.next_token()
            count = lex.next_token()
            if not (isinstance(start, int) and isinstance(count, int)):
                raise PDFError("malformed xref subsection header")
            lex.skip_ws()
            for i in range(count):
                line = d[lex.pos:lex.pos + 20]
                m = re.match(rb"(\d{10}) (\d{5}) ([nf])", line)
                if not m:
                    # tolerate non-standard spacing
                    mm = re.match(rb"\s*(\d+)\s+(\d+)\s+([nf])", d[lex.pos:lex.pos + 40])
                    if not mm:
                        raise PDFError("malformed xref entry")
                    o, g, t = int(mm.group(1)), int(mm.group(2)), mm.group(3)
                    lex.pos += mm.end()
                else:
                    o, g, t = int(m.group(1)), int(m.group(2)), m.group(3)
                    lex.pos += 18
                    lex.skip_ws()
                num = start + i
                entries[num] = ("n" if t == b"n" else "f", o, g)
        parser = Parser(d, lex.pos, resolver=self)
        trailer = parser.parse_object()
        if not isinstance(trailer, dict):
            raise PDFError("trailer is not a dictionary")
        return XrefSection(off, "table", trailer, entries)

    def _read_xref_stream(self, off: int, stm: Stream) -> XrefSection:
        data = decode_stream(stm, None)
        w = stm.get("W")
        if not (isinstance(w, list) and len(w) == 3):
            raise PDFError("xref stream /W invalid")
        size = stm.get("Size", 0)
        index = stm.get("Index") or [0, size]
        rowlen = sum(w)
        entries: Dict[int, Tuple[str, int, int]] = {}
        pos = 0

        def field_val(b: bytes) -> int:
            return int.from_bytes(b, "big") if b else 0

        for k in range(0, len(index), 2):
            start, count = index[k], index[k + 1]
            for i in range(count):
                row = data[pos:pos + rowlen]
                pos += rowlen
                if len(row) < rowlen:
                    break
                t = field_val(row[:w[0]]) if w[0] else 1
                f2 = field_val(row[w[0]:w[0] + w[1]])
                f3 = field_val(row[w[0] + w[1]:])
                num = start + i
                if t == 0:
                    entries[num] = ("f", f2, f3)
                elif t == 1:
                    entries[num] = ("n", f2, f3)
                elif t == 2:
                    entries[num] = ("c", f2, f3)
        trailer = dict(stm.dict)
        return XrefSection(off, "stream", trailer, entries)

    def _rebuild_by_scan(self) -> None:
        """Last resort for damaged files: scan for ``N G obj``."""
        self.warnings.append("xref damaged; rebuilt by scanning for objects")
        merged: Dict[int, Tuple[str, int, int]] = {}
        for m in re.finditer(rb"(?<![0-9])(\d+)\s+(\d+)\s+obj\b", self.data):
            merged[int(m.group(1))] = ("n", m.start(), int(m.group(2)))
        self.xref = merged
        tr = self.data.rfind(b"trailer")
        self.trailer = {}
        if tr >= 0:
            try:
                t = Parser(self.data, tr + 7, resolver=self).parse_object()
                if isinstance(t, dict):
                    self.trailer = t
            except PDFError:
                pass
        if "Root" not in self.trailer:
            for num in sorted(merged):
                try:
                    o = self.get_object(num)
                except PDFError:
                    continue
                if isinstance(o, dict) and o.get("Type") == "Catalog":
                    self.trailer["Root"] = Ref(num, 0)
        self.sections = [XrefSection(-1, "scan", self.trailer, dict(merged))]

    # ── object access ──────────────────────────────────────────────────────

    def get_object(self, num: int, gen: int = 0,
                   entries: Optional[Dict[int, Tuple[str, int, int]]] = None) -> Any:
        xref = self.xref if entries is None else entries
        key = (num, gen) if entries is None else None
        if key is not None and key in self._cache:
            return self._cache[key]
        ent = xref.get(num)
        if ent is None:
            return None
        kind, a, b = ent
        if kind == "f":
            return None
        if kind == "n":
            _, _, obj = Parser(self.data, resolver=self).parse_indirect_at(a)
        else:
            obj = self._from_objstm(a, b, num)
        if key is not None:
            self._cache[key] = obj
        return obj

    def _from_objstm(self, stm_num: int, index: int, num: int) -> Any:
        if stm_num not in self._objstm_cache:
            stm = self.get_object(stm_num)
            if not isinstance(stm, Stream):
                raise PDFError(f"object stream {stm_num} missing")
            data = decode_stream(stm, self)
            n = stm.get("N", 0)
            first = stm.get("First", 0)
            lex = Lexer(data)
            pairs = []
            for _ in range(n):
                onum = lex.next_token()
                ooff = lex.next_token()
                pairs.append((onum, ooff))
            objs: Dict[int, Any] = {}
            for onum, ooff in pairs:
                try:
                    objs[onum] = Parser(data, first + ooff, resolver=self).parse_object()
                except PDFError:
                    objs[onum] = None
            self._objstm_cache[stm_num] = objs
        return self._objstm_cache[stm_num].get(num)

    def resolve(self, x: Any, depth: int = 0) -> Any:
        while isinstance(x, Ref) and depth < 32:
            x = self.get_object(x.num, x.gen)
            depth += 1
        return x

    def object_offset(self, num: int) -> Optional[int]:
        ent = self.xref.get(num)
        if ent and ent[0] == "n":
            return ent[1]
        return None

    @property
    def root(self) -> Dict[str, Any]:
        r = self.resolve(self.trailer.get("Root"))
        return r if isinstance(r, dict) else {}

    @property
    def info(self) -> Dict[str, Any]:
        i = self.resolve(self.trailer.get("Info"))
        return i if isinstance(i, dict) else {}

    @property
    def encrypted(self) -> bool:
        return "Encrypt" in self.trailer

    # ── pages ──────────────────────────────────────────────────────────────

    def pages(self) -> List[Dict[str, Any]]:
        out: List[Dict[str, Any]] = []
        seen = set()

        def walk(node_ref: Any, inherited: Dict[str, Any], depth: int) -> None:
            if depth > 64:
                return
            node = self.resolve(node_ref)
            if not isinstance(node, dict):
                return
            if isinstance(node_ref, Ref):
                if node_ref in seen:
                    return
                seen.add(node_ref)
            inh = dict(inherited)
            for k in ("Resources", "MediaBox", "CropBox", "Rotate"):
                if k in node:
                    inh[k] = node[k]
            if node.get("Type") == "Pages" or "Kids" in node:
                for kid in self.resolve(node.get("Kids")) or []:
                    walk(kid, inh, depth + 1)
            else:
                page = dict(inh)
                page.update(node)
                out.append(page)

        walk(self.root.get("Pages"), {}, 0)
        return out

    # ── name trees ─────────────────────────────────────────────────────────

    def name_tree(self, node_ref: Any) -> List[Tuple[str, Any]]:
        out: List[Tuple[str, Any]] = []

        def walk(nref: Any, depth: int) -> None:
            node = self.resolve(nref)
            if not isinstance(node, dict) or depth > 32:
                return
            names = self.resolve(node.get("Names"))
            if isinstance(names, list):
                for i in range(0, len(names) - 1, 2):
                    k = self.resolve(names[i])
                    key = k.text() if isinstance(k, PDFString) else str(k)
                    out.append((key, names[i + 1]))
            for kid in self.resolve(node.get("Kids")) or []:
                walk(kid, depth + 1)

        walk(node_ref, 0)
        return out


