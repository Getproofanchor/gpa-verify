@dataclass
class RawImage:
    width: int
    height: int
    channels: int
    pixels: bytes          # 8-bit samples, row-major
    ref: Optional[Ref] = None


def iter_page_images(doc: PDFDocument, page: Dict[str, Any],
                     max_side: int = 1200) -> Iterator[RawImage]:
    """Yield decodable (Flate/uncompressed, 8-bit Gray/RGB) image XObjects."""
    res = doc.resolve(page.get("Resources")) or {}
    xo = doc.resolve(res.get("XObject")) if isinstance(res, dict) else None
    if not isinstance(xo, dict):
        return
    for _, ref in xo.items():
        obj = doc.resolve(ref)
        if not isinstance(obj, Stream) or obj.get("Subtype") != "Image":
            continue
        w, h = obj.get("Width"), obj.get("Height")
        bpc = obj.get("BitsPerComponent", 8)
        cs = doc.resolve(obj.get("ColorSpace"))
        if not (isinstance(w, int) and isinstance(h, int)) or max(w, h) > max_side:
            continue
        if bpc != 8:
            continue
        ch = {"DeviceRGB": 3, "DeviceGray": 1, "CalRGB": 3, "CalGray": 1}.get(
            str(cs) if isinstance(cs, Name) else "", None)
        if ch is None:
            continue
        try:
            data = decode_stream(obj, doc)
        except PDFError:
            continue
        if len(data) < w * h * ch:
            continue
        yield RawImage(w, h, ch, data[:w * h * ch], ref if isinstance(ref, Ref) else None)
